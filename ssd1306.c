/* SSD1306 命令 */
#define SSD1306_SET_CONTRAST        0x81
#define SSD1306_DISPLAY_ON          0xAF
#define SSD1306_DISPLAY_OFF         0xAE
#define SSD1306_NORMAL_DISPLAY      0xA6
#define SSD1306_INVERT_DISPLAY      0xA7
#define SSD1306_SET_MUX_RATIO       0xA8
#define SSD1306_SET_DISPLAY_OFFSET   0xD3
#define SSD1306_SET_DISPLAY_START_LINE  0x40
#define SSD1306_SET_SEG_REMAP       0xA1
#define SSD1306_SET_COM_SCAN_DIR    0xC8
#define SSD1306_SET_COM_PINS        0xDA
#define SSD1306_SET_PAGE_ADDR       0xB0
#define SSD1306_SET_COL_ADDR_LOW    0x00
#define SSD1306_SET_COL_ADDR_HIGH   0x10
#define SSD1306_SET_CLK_DIV         0xD5
#define SSD1306_SET_PRECHARGE       0xD9
#define SSD1306_SET_VCOM_DESEL      0xDB
#define SSD1306_CHARGE_PUMP         0x8D

/* I2C 控制字节 */
#define SSD1306_I2C_CMD   0x00
#define SSD1306_I2C_DATA  0x40

static uint8_t ssd1306_buf[SSD1306_BUF_SIZE];
static uint8_t cursor_x = 0, cursor_y = 0;

extern I2C_HandleTypeDef SSD1306_I2C_PORT;

static void ssd1306_WriteCmd(uint8_t cmd)
{
    uint8_t b[2] = { SSD1306_I2C_CMD, cmd };
    HAL_I2C_Master_Transmit(&SSD1306_I2C_PORT, SSD1306_I2C_ADDR, b, 2, 10);
}

static void ssd1306_WriteData(uint8_t *p, uint16_t n)
{
    static uint8_t tmp[SSD1306_BUF_SIZE + 1];
    tmp[0] = SSD1306_I2C_DATA;
    for (uint16_t i = 0; i < n; i++) tmp[i + 1] = p[i];
    HAL_I2C_Master_Transmit(&SSD1306_I2C_PORT, SSD1306_I2C_ADDR, tmp, n + 1, 50);
}

