void ssd1306_Init(void)
{
    HAL_Delay(50);  /* 上电等待 */

    ssd1306_WriteCmd(SSD1306_DISPLAY_OFF);
    ssd1306_WriteCmd(SSD1306_SET_MUX_RATIO);    ssd1306_WriteCmd(0x3F);
    ssd1306_WriteCmd(SSD1306_SET_DISPLAY_OFFSET); ssd1306_WriteCmd(0x00);
    ssd1306_WriteCmd(SSD1306_SET_DISPLAY_START_LINE);
    ssd1306_WriteCmd(SSD1306_SET_SEG_REMAP);
    ssd1306_WriteCmd(SSD1306_SET_COM_SCAN_DIR);
    ssd1306_WriteCmd(SSD1306_SET_COM_PINS);     ssd1306_WriteCmd(0x12);
    ssd1306_WriteCmd(SSD1306_SET_CONTRAST);     ssd1306_WriteCmd(0xCF);
    ssd1306_WriteCmd(SSD1306_SET_CLK_DIV);     ssd1306_WriteCmd(0x80);
    ssd1306_WriteCmd(SSD1306_SET_PRECHARGE);    ssd1306_WriteCmd(0xF1);
    ssd1306_WriteCmd(SSD1306_SET_VCOM_DESEL);  ssd1306_WriteCmd(0x40);
    ssd1306_WriteCmd(SSD1306_CHARGE_PUMP);      ssd1306_WriteCmd(0x14);
    ssd1306_WriteCmd(SSD1306_NORMAL_DISPLAY);
    ssd1306_WriteCmd(SSD1306_DISPLAY_ON);
}

void ssd1306_Fill(SSD1306_Color color)
{
    uint8_t v = (color == White) ? 0xFF : 0x00;
    for (uint16_t i = 0; i < SSD1306_BUF_SIZE; i++) ssd1306_buf[i] = v;
}

void ssd1306_UpdateScreen(void)
{
    for (uint8_t page = 0; page < 8; page++) {
        ssd1306_WriteCmd(SSD1306_SET_PAGE_ADDR | page);
        ssd1306_WriteCmd(SSD1306_SET_COL_ADDR_LOW);
        ssd1306_WriteCmd(SSD1306_SET_COL_ADDR_HIGH);
        ssd1306_WriteData(&ssd1306_buf[page * SSD1306_WIDTH], SSD1306_WIDTH);
    }
}

void ssd1306_SetCursor(uint8_t x, uint8_t y)
{
    if (x >= SSD1306_WIDTH)  x = SSD1306_WIDTH  - 1;
    if (y >= SSD1306_HEIGHT) y = SSD1306_HEIGHT - 1;
    cursor_x = x;
    cursor_y = y;
}

char ssd1306_WriteChar(char ch, SSD1306_Color color)
{
    if (ch < ' ' || ch > '~') ch = ' ';
    const uint8_t *glyph = font5x7[ch - ' '];

    for (uint8_t i = 0; i < 5; i++) {
        uint8_t col_x = cursor_x + i;
        if (col_x >= SSD1306_WIDTH) break;

        uint8_t col = (color == White) ? glyph[i] : (~glyph[i] & 0x7F);
        uint8_t page = cursor_y / 8;
        uint8_t bit_in_page = cursor_y % 8;

        if (color == White) {
            ssd1306_buf[page * SSD1306_WIDTH + col_x] |=  (col << bit_in_page);
            if (bit_in_page && (page + 1) < 8)
                ssd1306_buf[(page + 1) * SSD1306_WIDTH + col_x] |= (col >> (8 - bit_in_page));
        } else {
            ssd1306_buf[page * SSD1306_WIDTH + col_x] &= ~(0x7F << bit_in_page);
            if (bit_in_page && (page + 1) < 8)
                ssd1306_buf[(page + 1) * SSD1306_WIDTH + col_x] &= ~(0x7F >> (8 - bit_in_page));
        }
    }
    cursor_x += (SSD1306_FONT_WIDTH + 1);
    return ch;
}

void ssd1306_WriteString(const char *str, SSD1306_Color color)
{
    while (*str) ssd1306_WriteChar(*str++, color);
}
